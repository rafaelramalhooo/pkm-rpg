export const slugHab = (nome: string): string => nome.toLowerCase().replace(/[^a-z0-9]+/g, "");
const PORID: Record<string, [string, string]> = Object.fromEntries(Object.entries(HAB).map(([k, v]) => [slugHab(k), v]));
export const nomeHab = (slugOuNome: string): string => PORID[slugHab(slugOuNome)]?.[0] ?? slugOuNome;
export const descHab = (slugOuNome: string): string => PORID[slugHab(slugOuNome)]?.[1] ?? "";

let cache: Map<number, Record<number, string>> | null = null;
/** Habilidades por espécie e slot (1 e 2 comuns, 3 oculta). Carrega a tabela uma vez só. */
export async function habilidadesDe(especieId: number): Promise<Record<number, string>> {
  if (!cache) {
    cache = new Map();
    const { data } = await supabase.from("especie_habilidades").select("especie_id, slot, nome").limit(2000);
    for (const r of (data ?? []) as { especie_id: number; slot: number; nome: string }[]) {
      const x = cache.get(r.especie_id) ?? {};
      x[r.slot] = r.nome;
      cache.set(r.especie_id, x);
    }
  }
  return cache.get(especieId) ?? {};
}
